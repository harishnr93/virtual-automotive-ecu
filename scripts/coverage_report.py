#!/usr/bin/env python3
"""Summarises gcov data of a coverage build into docs/coverage_report.md (no lcov/gcovr needed).

    ./scripts/coverage_report.py build-coverage                # after running the tests
    ./scripts/coverage_report.py build-coverage --report /tmp/coverage.md

Reads every .gcda file of the build with `gcov --json-format --stdout`, merges the results per
source file (a header compiled into several objects counts as covered where any object ran it)
and reports line and function coverage for the product code: include/, src/ and apps/. Test
code is excluded. Exits with code 1 if the line coverage is below --fail-under.
"""

import argparse
import datetime
import gzip
import json
import pathlib
import subprocess
import sys
from collections import defaultdict

REPO = pathlib.Path(__file__).resolve().parents[1]
PRODUCT_DIRS = ("include/", "src/", "apps/")


def gcov_json(gcda: pathlib.Path):
    result = subprocess.run(["gcov", "--json-format", "--stdout", "--object-directory", str(gcda.parent), str(gcda)],
                            capture_output=True, cwd=gcda.parent, timeout=120)
    if result.returncode != 0:
        raise RuntimeError(f"gcov failed for {gcda}: {result.stderr.decode()[:500]}")
    out = result.stdout
    if out[:2] == b"\x1f\x8b":
        out = gzip.decompress(out)
    for line in out.decode().splitlines():  # one JSON document per line
        if line.strip():
            yield json.loads(line)


def relative(path: str, cwd: str) -> str:
    p = pathlib.Path(path)
    if not p.is_absolute():
        p = pathlib.Path(cwd) / p
    try:
        return str(p.resolve().relative_to(REPO))
    except ValueError:
        return ""


def collect(build: pathlib.Path):
    lines = defaultdict(dict)       # file -> line -> max count
    functions = defaultdict(dict)   # file -> (start_line, name) -> max count
    gcda_files = sorted(build.rglob("*.gcda"))
    if not gcda_files:
        raise SystemExit(f"no .gcda files under {build}: build with -DVECU_ENABLE_COVERAGE=ON and run the tests")
    for gcda in gcda_files:
        for doc in gcov_json(gcda):
            cwd = doc.get("current_working_directory", str(gcda.parent))
            for entry in doc.get("files", []):
                rel = relative(entry["file"], cwd)
                if not rel.startswith(PRODUCT_DIRS):
                    continue
                for line in entry.get("lines", []):
                    number = line["line_number"]
                    lines[rel][number] = max(lines[rel].get(number, 0), line["count"])
                for fn in entry.get("functions", []):
                    key = (fn["start_line"], fn.get("demangled_name", fn["name"]))
                    functions[rel][key] = max(functions[rel].get(key, 0), fn["execution_count"])
    return lines, functions, len(gcda_files)


def module_of(path: str) -> str:
    parts = path.split("/")
    if parts[0] == "apps":
        return f"apps/{parts[1]}"
    return parts[1] if len(parts) > 2 else parts[0]


def pct(covered: int, total: int) -> str:
    return f"{100.0 * covered / total:.1f} %" if total else "–"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("build", type=pathlib.Path)
    parser.add_argument("--report", type=pathlib.Path, default=REPO / "docs" / "coverage_report.md")
    parser.add_argument("--fail-under", type=float, default=0.0, help="minimum line coverage in percent")
    args = parser.parse_args()

    lines, functions, n_gcda = collect(args.build.resolve())
    rows = []
    for path in sorted(lines):
        total = len(lines[path])
        covered = sum(1 for c in lines[path].values() if c > 0)
        fn_total = len(functions[path])
        fn_covered = sum(1 for c in functions[path].values() if c > 0)
        rows.append((path, covered, total, fn_covered, fn_total))
    modules = defaultdict(lambda: [0, 0, 0, 0])
    for path, c, t, fc, ft in rows:
        m = modules[module_of(path)]
        m[0] += c
        m[1] += t
        m[2] += fc
        m[3] += ft
    all_c, all_t = sum(r[1] for r in rows), sum(r[2] for r in rows)
    all_fc, all_ft = sum(r[3] for r in rows), sum(r[4] for r in rows)

    uncovered_fns = sorted((path, line, name) for path in functions for (line, name), count in functions[path].items()
                           if count == 0)
    out = [
        "# Coverage Report", "",
        f"Generated by `scripts/run_coverage.sh` on {datetime.datetime.now():%Y-%m-%d %H:%M} from {n_gcda} gcov data "
        "files: **all tests** (C++ unit and integration, Python unit and system tests that start the real ECU "
        "processes). Product code only (`include/`, `src/`, `apps/`); test code is excluded. GCC `--coverage -O0`.", "",
        f"**Total: {pct(all_c, all_t)} of lines ({all_c} / {all_t}), {pct(all_fc, all_ft)} of functions "
        f"({all_fc} / {all_ft}).**", "",
        "Line coverage says which code ran during the tests, not that its behaviour was checked; the assertions are "
        "in the tests. Inline/template functions are counted once per source location.", "",
        "## By module", "", "| Module | Lines | Functions |", "|---|---|---|"]
    for name in sorted(modules):
        c, t, fc, ft = modules[name]
        out.append(f"| `{name}` | {pct(c, t)} ({c} / {t}) | {pct(fc, ft)} ({fc} / {ft}) |")
    out += ["", "## By file", "", "| File | Lines | Functions |", "|---|---|---|"]
    for path, c, t, fc, ft in sorted(rows, key=lambda r: (r[1] / r[2] if r[2] else 1.0, r[0])):
        out.append(f"| `{path}` | {pct(c, t)} ({c} / {t}) | {pct(fc, ft)} ({fc} / {ft}) |")
    out += ["", f"## Functions never executed ({len(uncovered_fns)})", "",
            "Each is either untested behaviour or code that tests cannot reach on this host (e.g. SocketCAN without "
            "`vcan0`, real-time scheduling without the permission).", ""]
    out += [f"- `{path}:{line}` {name}" for path, line, name in uncovered_fns]
    args.report.write_text("\n".join(out) + "\n")
    print(f"line coverage {pct(all_c, all_t)} ({all_c}/{all_t}), function coverage {pct(all_fc, all_ft)} "
          f"({all_fc}/{all_ft}) -> {args.report}")
    return 1 if all_t and 100.0 * all_c / all_t < args.fail_under else 0


if __name__ == "__main__":
    sys.exit(main())
